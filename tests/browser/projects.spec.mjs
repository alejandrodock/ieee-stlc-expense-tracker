import { test, expect } from '@playwright/test';
import { PDFDocument, PDFName } from 'pdf-lib';

test('mobile project switch, STLC isolation, EUR receipt, USD 18 affidavit and offline manual rate', async ({ page, request }) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Cada proyecto, sus cuentas.' })).toBeVisible();
  await page.getByRole('link', { name: /Conferencia STLC 2026/ }).click();
  await expect(page.getByText('Proveedor STLC histórico')).toBeVisible();
  await expect(page.getByText('Proveedor HART previo')).toHaveCount(0);
  await expect.poll(() => page.evaluate(() => localStorage.getItem('ieee:active-project'))).toBe('STLC');
  const old = await (await request.get('/api/gastos')).json();
  expect(old).toHaveLength(1); expect(old[0].monto_bob).toBe(115.8); expect(old[0].monto_usd).toBe(10);
  const wrongDelete = await request.delete('/api/gastos', { data: { id: '623ca6f5-70ca-4fa7-95a0-41aec20238cd' } });
  expect(wrongDelete.status()).toBe(404);
  const wrongHartDelete = await request.delete('/api/hart/gastos', { data: { id: old[0].id } });
  expect(wrongHartDelete.status()).toBe(404);
  expect((await request.get(`/api/hart/comprobantes/${old[0].id}`)).status()).toBe(404);
  expect((await request.get('/api/comprobantes/623ca6f5-70ca-4fa7-95a0-41aec20238cd')).status()).toBe(404);

  await page.getByRole('link', { name: 'HART 2026', exact: true }).click();
  await expect(page.getByText('Proveedor HART previo')).toBeVisible();
  await expect(page.getByText('Proveedor STLC histórico')).toHaveCount(0);
  await expect.poll(() => page.evaluate(() => localStorage.getItem('ieee:active-project'))).toBe('HART');
  await page.reload();
  await expect(page.getByRole('heading', { name: 'IEEE HART', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();

  await page.route('**/api/hart/rates?currency=EUR', route => route.fulfill({ json: { rate: 1.15, date: '2026-11-13T00:00:00Z', source: 'api' } }));
  await page.getByRole('button', { name: 'Nuevo gasto' }).click();
  await page.getByLabel('Proveedor', { exact: true }).fill('Compra EUR de prueba');
  await page.getByLabel('Monto original', { exact: true }).fill('30');
  await page.getByRole('combobox', { name: 'Moneda', exact: true }).selectOption('EUR');
  await expect(page.getByLabel('Tipo de cambio: USD por 1 EUR')).toHaveValue('1.15');
  const doc = await PDFDocument.create(); doc.addPage();
  await page.getByLabel('PDF del comprobante', { exact: true }).setInputFiles({ name: 'recibo.pdf', mimeType: 'application/pdf', buffer: Buffer.from(await doc.save()) });
  await page.getByRole('button', { name: 'Guardar gasto', exact: true }).click();
  await expect(page.getByRole('form', { name: 'Nuevo gasto HART' })).toHaveCount(0);
  await expect(page.getByText('Compra EUR de prueba', { exact: true })).toBeVisible();
  let rows = await (await request.get('/api/hart/gastos')).json();
  const eur = rows.find(e => e.proveedor === 'Compra EUR de prueba');
  expect(eur.original_currency).toBe('EUR'); expect(eur.exchange_rate).toBe(1.15); expect(eur.amount_usd).toBe(34.5);
  const receipt = await request.get(eur.pdf_url); expect(receipt.ok()).toBeTruthy();
  expect((await PDFDocument.load(await receipt.body())).getPageCount()).toBe(2);

  await page.getByRole('button', { name: 'Nuevo gasto' }).click();
  await page.getByLabel('Proveedor', { exact: true }).fill('Taxi HART 18 USD');
  await page.getByRole('combobox', { name: 'Categoría', exact: true }).selectOption('transporte');
  await page.getByLabel('Descripción / motivo del gasto').fill('Taxi al evento HART');
  await page.getByLabel('Monto original', { exact: true }).fill('25');
  await page.getByLabel('Tengo factura o recibo oficial').uncheck();
  await expect(page.getByText('Desde 25,00 USD debes adjuntar')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Guardar gasto', exact: true })).toBeDisabled();
  await page.getByLabel('Monto original', { exact: true }).fill('18');
  await page.getByLabel('Nombre completo del declarante').fill('Voluntario de prueba');
  const canvas = page.getByLabel('Firma de la declaración', { exact: true });
  await canvas.scrollIntoViewIfNeeded(); const box = await canvas.boundingBox();
  await page.mouse.move(box.x + 20, box.y + 60); await page.mouse.down();
  for (let x = 20; x < 230; x += 5) await page.mouse.move(box.x + x, box.y + 70 + Math.sin(x / 10) * 20);
  await page.mouse.up();
  await expect(page.getByText('Firma capturada', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Guardar gasto', exact: true }).click();
  await expect(page.getByRole('form', { name: 'Nuevo gasto HART' })).toHaveCount(0);
  rows = await (await request.get('/api/hart/gastos')).json();
  const taxi = rows.find(e => e.proveedor === 'Taxi HART 18 USD'); expect(taxi.amount_usd).toBe(18); expect(taxi.has_receipt).toBe(false);
  const affidavit = await PDFDocument.load(await (await request.get(taxi.pdf_url)).body());
  expect(affidavit.getSubject()).toBe('IEEE Expense Affidavit');
  expect(affidavit.getPage(0).node.Resources().lookup(PDFName.of('XObject')).keys().length).toBeGreaterThan(0);
  expect((await (await request.get('/api/gastos')).json())).toEqual(old);
  await page.screenshot({ path: 'test-results/hart-mobile.png', fullPage: true });

  await page.route('**/api/hart/rates?currency=BOB', route => route.fulfill({ status: 503, json: { error: 'Sin conexión: introduce una tasa manual.' } }));
  await page.getByRole('button', { name: 'Nuevo gasto' }).click();
  await page.getByRole('combobox', { name: 'Moneda', exact: true }).selectOption('BOB');
  await expect(page.getByText('Sin conexión: introduce una tasa manual.')).toBeVisible();
  await page.getByLabel('Monto original', { exact: true }).fill('100');
  await page.getByLabel('Tipo de cambio: USD por 1 BOB').fill('0.14');
  await page.getByRole('button', { name: 'Cerrar', exact: true }).click();
  await page.getByRole('link', { name: 'STLC 2026', exact: true }).click();
  await expect(page.getByText('Proveedor STLC histórico')).toBeVisible();
  await page.getByRole('link', { name: 'HART 2026', exact: true }).click();
  await page.getByRole('button', { name: 'Nuevo gasto' }).click();
  await expect(page.getByLabel('Monto original', { exact: true })).toHaveValue('100');
  await expect(page.getByLabel('Tipo de cambio: USD por 1 BOB')).toHaveValue('0.14');
});
