import { test, expect } from '@playwright/test';
const token = id => ({ admin: 'a', ivan: 'i', fabian: 'f', eloy: 'e' })[id].repeat(43);
const headers = id => ({ Authorization: `Bearer ${token(id)}` });
test('personal links, rubric, fixed pitch, immutable receipt, results and mobile layout', async ({ page, request }) => {
  expect((await request.get('/api/hackathon')).status()).toBe(401);
  expect((await request.get('/api/hackathon', { headers: { Authorization: `Bearer ${'x'.repeat(43)}` } })).status()).toBe(401);
  await page.goto(`/hackathon#acceso=${token('ivan')}`);
  await expect(page.getByRole('heading', { name: 'Telecom Innovation Hackathon' })).toBeVisible();
  await expect(page.getByText('De la idea al impacto.')).toHaveCount(0);
  await expect(page.getByText('IVAN ALEJANDRO MENDOZA MENDOZA', { exact: true })).toBeVisible();
  await page.getByLabel('Selecciona el equipo').selectOption('tilcayos');
  await expect(page.getByText('Sin nota previa')).toHaveCount(5);
  await expect(page.locator('#score-0')).toHaveValue('');
  await expect(page.locator('#score-5')).toHaveValue('95');
  await expect(page.locator('#score-5')).toHaveAttribute('readonly', '');
  await expect(page.getByRole('link', { name: 'Whitepaper / Roadmap' })).toHaveAttribute('href', /1LhD5/);
  await expect(page.getByRole('button', { name: 'Enviar evaluación definitiva' })).toBeDisabled();
  for (let i = 0; i < 5; i++) await page.locator(`#score-${i}`).fill('80');
  await expect(page.getByText('81,50', { exact: false })).toBeVisible();
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Enviar evaluación definitiva' }).click();
  await expect(page.getByRole('heading', { name: 'Evaluación registrada' })).toBeVisible();
  await page.reload();
  await page.getByLabel('Selecciona el equipo').selectOption('tilcayos');
  await expect(page.getByRole('heading', { name: 'Evaluación registrada' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Enviar evaluación definitiva' })).toHaveCount(0);
  const duplicate = await request.post('/api/hackathon', { headers: headers('ivan'), data: { teamId: 'tilcayos', scores: [100,100,100,100,100], confirmed: true } });
  expect(duplicate.status()).toBe(409);
  const invalid = await request.post('/api/hackathon', { headers: headers('fabian'), data: { teamId: 'ldg', scores: [101,80,80,80,80], confirmed: true } });
  expect(invalid.status()).toBe(400);
  const sixth = await request.post('/api/hackathon', { headers: headers('fabian'), data: { teamId: 'ldg', scores: [80,80,80,80,80,100], confirmed: true } });
  expect(sixth.status()).toBe(400);
  const attempts = await Promise.all([80,90].map(n => request.post('/api/hackathon', { headers: headers('eloy'), data: { teamId: 'novax', scores: [n,n,n,n,n], confirmed: true, judgeId: 'ivan', total: 100, pitch: 100 } })));
  expect(attempts.map(r => r.status()).sort()).toEqual([201,409]);
  const winner = (await attempts.find(r => r.status() === 201).json()).submission;
  expect(winner.judgeId).toBe('eloy'); expect(winner.scores[5]).toBe(95);
  expect(winner.total).toBe(winner.scores[0] * .9 + 9.5);
  const own = await (await request.get('/api/hackathon', { headers: headers('ivan') })).json();
  expect(own.submissions).toHaveLength(1); expect(own.submissions[0].total).toBe(81.5);
  expect(own.submissions.every(s => s.judgeId === 'ivan')).toBe(true);
  await page.goto(`/hackathon#acceso=${token('fabian')}`);
  await expect(page.getByText('MARCO FABIAN BORDA WIEGERT', { exact: true })).toBeVisible();
  await page.getByLabel('Selecciona el equipo').selectOption('ldg');
  await expect(page.locator('#score-0')).toHaveValue('80');
  await expect(page.locator('#score-5')).toHaveValue('70');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/hackathon-mobile.png', fullPage: true });
  const anotherJudge = await request.post('/api/hackathon', { headers: headers('fabian'), data: { teamId: 'tilcayos', scores: [60,60,60,60,60], confirmed: true } });
  expect(anotherJudge.status()).toBe(201);
  await page.goto(`/hackathon#acceso=${token('admin')}`); await page.reload();
  await expect(page.getByText('3 / 15 evaluaciones registradas')).toBeVisible();
  await expect(page.getByText('Resultados provisionales.', { exact: true })).toBeVisible();
  const detail = page.getByRole('table', { name: 'Puntajes y ponderaciones de Los Tilcayos 2.0' });
  await expect(detail.getByRole('columnheader', { name: 'IVAN ALEJANDRO MENDOZA MENDOZA' })).toBeVisible();
  await expect(detail.getByRole('row', { name: /Innovación y originalidad/ }).getByRole('cell')).toHaveText(['20 %', '80,00', '16,00', '60,00', '12,00', 'Pendiente', '—', '70,00', '14,00']);
  await expect(detail.getByRole('row', { name: /Total ponderado/ }).getByRole('cell')).toHaveText(['100 %', '81,50', '62,50', '—', '72,00']);
  await expect(detail.getByRole('row', { name: /Presentación y demostración/ }).getByRole('cell')).toHaveText(['10 %', '95,00', '9,50', '85,00', '8,50', 'Pendiente', '—', '90,00', '9,00']);
  await page.getByLabel('Equipo para ver resultados detallados').selectOption('ldg');
  const pending = page.getByRole('table', { name: 'Puntajes y ponderaciones de LDG' });
  await expect(pending.getByRole('row', { name: /Total ponderado/ }).getByRole('cell')).toHaveText(['100 %', '—', '—', '—', '—']);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByLabel('Equipo para ver resultados detallados').selectOption('tilcayos');
  const downloadPromise = page.waitForEvent('download'); await page.getByRole('button', { name: 'Exportar CSV' }).click();
  const downloaded = await downloadPromise;
  expect(downloaded.suggestedFilename()).toBe('telecom-hackathon-evaluaciones.csv');
  const stream = await downloaded.createReadStream();
  const chunks = []; for await (const chunk of stream) chunks.push(chunk);
  const csv = Buffer.concat(chunks).toString('utf8');
  expect(csv).toContain('Innovación y originalidad aporte ponderado');
  expect(csv).toContain('IVAN ALEJANDRO MENDOZA MENDOZA');
  expect(csv).toContain('"80";"20";"16"');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'test-results/hackathon-results.png', fullPage: true });
  expect((await request.post('/api/hackathon', { headers: headers('admin'), data: { teamId: 'ldg', scores: [80,80,80,80,80], confirmed: true } })).status()).toBe(403);
});
